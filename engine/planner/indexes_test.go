const parentIndexName = "orders_created_at_idx"

// TestIndexConditionClassification is FR-PLAN-4: absent plus the four states
// the three pg_index flags can put an existing index in.
func TestIndexConditionClassification(t *testing.T) {
	tests := []struct {
		name                    string
		valid, ready, live      bool
		want                    IndexCondition
		wantUsable, wantCleanup bool
	}{
		{"valid ready live", true, true, true, IndexValid, true, false},
		{"interrupted CIC leaves indisvalid false", false, true, true, IndexInvalid, false, true},
		{"build still in flight", true, false, true, IndexNotReady, false, true},
		{"drop in flight", true, true, false, IndexNotLive, false, true},
		{"not live wins over not valid", false, false, false, IndexNotLive, false, true},
		{"not valid wins over not ready", false, false, true, IndexInvalid, false, true},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			i := idx(1, "public", "x", 2, "t", tc.valid, tc.ready, tc.live)
			if got := i.Condition(); got != tc.want {
				t.Fatalf("Condition() = %q, want %q", got, tc.want)
			}
			if got := tc.want.Usable(); got != tc.wantUsable {
				t.Errorf("%q.Usable() = %v, want %v", tc.want, got, tc.wantUsable)
			}
			if got := tc.want.NeedsCleanup(); got != tc.wantCleanup {
				t.Errorf("%q.NeedsCleanup() = %v, want %v", tc.want, got, tc.wantCleanup)
			}
		})
	}

	t.Run("absent is neither usable nor cleanable", func(t *testing.T) {
		if IndexAbsent.Usable() || IndexAbsent.NeedsCleanup() {
			t.Error("IndexAbsent should require nothing")
		}
	})

	t.Run("every condition is enumerated", func(t *testing.T) {
		all := AllIndexConditions()
		if len(all) != 5 {
			t.Fatalf("AllIndexConditions() = %v, want 5 entries", all)
		}
		seen := map[IndexCondition]bool{}
		for _, c := range all {
			if seen[c] {
				t.Errorf("duplicate condition %q", c)
			}
			seen[c] = true
			if c.String() != string(c) {
				t.Errorf("String() = %q", c.String())
			}
		}
	})
}

// TestInspectChildrenDetectsEveryState is the FR-PLAN-4 sweep across one tree:
// each leaf carries an index in a different state, plus one with none at all.
func TestInspectChildrenDetectsEveryState(t *testing.T) {
	leaves := []string{"orders_absent", "orders_valid", "orders_invalid", "orders_notready", "orders_notlive"}
	f := tree(protocol.StrategyRange, leaves...)
	topo := mustDiscover(t, f)

	parentIdx := Index{
		OID: indexBase, Name: name("public", parentIndexName), Kind: RelKindPartitionedIndex,
		OwnerOID: ownerOID, TableOID: rootOID, Table: name("public", "orders"),
		IsValid: false, IsReady: true, IsLive: true,
	}
	f.AddIndex(parentIdx)

	// leaves[0] deliberately has no index at all.
	states := []struct {
		leaf               int
		valid, ready, live bool
		attach             bool
		want               IndexCondition
	}{
		{1, true, true, true, true, IndexValid},
		{2, false, true, true, false, IndexInvalid},
		{3, true, false, true, false, IndexNotReady},
		{4, true, true, false, false, IndexNotLive},
	}
	for _, s := range states {
		leafRel := topo.Leaves[s.leaf]
		child := idx(indexBase+10+uint32(s.leaf), "public",
			protocol.ChildIndexName(parentIndexName, leafRel.Name.Name),
			leafRel.OID, leafRel.Name.Name, s.valid, s.ready, s.live)
		if s.attach {
			child.ParentIndexOID = parentIdx.OID
		}
		f.AddIndex(child)
	}

	in, err := InspectChildren(ctx(), f, topo, name("public", parentIndexName))
	if err != nil {
		t.Fatalf("InspectChildren: %v", err)
	}
	if in.ParentIndex == nil || in.ParentIndex.OID != parentIdx.OID {
		t.Fatalf("ParentIndex = %+v, want the partitioned index", in.ParentIndex)
	}
	if len(in.Children) != len(leaves) {
		t.Fatalf("Children = %d, want %d", len(in.Children), len(leaves))
	}

	if in.Children[0].Exists() {
		t.Errorf("leaf %s should have no index", in.Children[0].Leaf)
	}
	if got := in.Children[0].Condition; got != IndexAbsent {
		t.Errorf("absent leaf condition = %q", got)
	}
	for _, s := range states {
		c := in.Children[s.leaf]
		if !c.Exists() {
			t.Fatalf("leaf %s has no index", c.Leaf)
		}
		if c.Condition != s.want {
			t.Errorf("leaf %s condition = %q, want %q", c.Leaf, c.Condition, s.want)
		}
		if got := c.AttachedTo(parentIdx.OID); got != s.attach {
			t.Errorf("leaf %s AttachedTo = %v, want %v", c.Leaf, got, s.attach)
		}
	}

	// FR-PLAN-5: only the one valid, attached leaf is complete.
	if got := in.CompleteCount(); got != 1 {
		t.Errorf("CompleteCount = %d, want 1", got)
	}
	if got := len(in.Remaining()); got != len(leaves)-1 {
		t.Errorf("Remaining = %d, want %d", got, len(leaves)-1)
	}
}

// TestInspectChildrenNames covers FR-PLAN-11 and FR-PLAN-13: names are
// generated by the planner, live in the leaf's schema, and are recorded rather
// than re-derived.
func TestInspectChildrenNames(t *testing.T) {
	f := standardTree()
	topo := mustDiscover(t, f)

	in, err := InspectChildren(ctx(), f, topo, name("public", parentIndexName))
	if err != nil {
		t.Fatalf("InspectChildren: %v", err)
	}
	for i, c := range in.Children {
		want := childIndex(t, parentIndexName, topo.Leaves[i].Name.Name)
		if c.ChildIndex != want {
			t.Errorf("child %d = %v, want %v", i, c.ChildIndex, want)
		}
		if c.ChildIndex.Schema != c.Leaf.Name.Schema {
			t.Errorf("child index %v is not in its leaf's schema %q", c.ChildIndex, c.Leaf.Name.Schema)
		}
		if err := c.ChildIndex.Validate(); err != nil {
			t.Errorf("generated name %v is not a legal identifier: %v", c.ChildIndex, err)
		}
	}
}

// TestInspectChildrenRejectsNameCollision: FR-PLAN-13 wants a plan-time error,
// never a silent overwrite.
func TestInspectChildrenRejectsNameCollision(t *testing.T) {
	// Two partitions whose names differ only past the truncation point, under
	// a parent index name long enough to force truncation, still get distinct
	// names because the tag hashes the untruncated inputs. Proving the
	// collision path therefore needs two identical partition names, which the
	// catalog cannot produce; assert the guarantee ChildIndexNames gives
	// instead.
	long := strings.Repeat("p", 55)
	f := tree(protocol.StrategyRange, long+"_january", long+"_february")
	topo := mustDiscover(t, f)

	in, err := InspectChildren(ctx(), f, topo, name("public", parentIndexName))
	if err != nil {
		t.Fatalf("InspectChildren: %v", err)
	}
	a, b := in.Children[0].ChildIndex, in.Children[1].ChildIndex
	if a == b {
		t.Fatalf("two partitions collided on %v", a)
	}
	for _, n := range []protocol.ObjectName{a, b} {
		if len(n.Name) > protocol.MaxIdentifierBytes {
			t.Errorf("%v is %d bytes, over the identifier limit", n, len(n.Name))
		}
	}
}

