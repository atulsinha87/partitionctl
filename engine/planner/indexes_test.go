// TestDecideCleanup is FR-PLAN-6 versus FR-PLAN-7: provenance decides whether
// an unusable index is dropped or the run halts (AC-5, AC-6, NFR-REL-3).
func TestDecideCleanup(t *testing.T) {
	f := standardTree()
	topo := mustDiscover(t, f)
	leaf := topo.Leaves[0]
	childName := childIndex(t, parentIndexName, leaf.Name.Name)

	plan := func(cond IndexCondition) ChildIndexPlan {
		c := ChildIndexPlan{Leaf: leaf, ChildIndex: childName, Condition: cond}
		if cond != IndexAbsent {
			existing := idx(indexBase+1, childName.Schema, childName.Name, leaf.OID, leaf.Name.Name,
				cond != IndexInvalid, cond != IndexNotReady, cond != IndexNotLive)
			c.Existing = &existing
		}
		return c
	}

	tests := []struct {
		name     string
		cond     IndexCondition
		prov     ProvenanceLookup
		want     CleanupDecision
		wantHalt bool
	}{
		{
			name: "absent needs nothing",
			cond: IndexAbsent, prov: NewFakeProvenance(childName), want: CleanupNone,
		},
		{
			name: "valid needs nothing",
			cond: IndexValid, prov: NewFakeProvenance(childName), want: CleanupNone,
		},
		{
			name: "invalid with provenance is dropped (FR-PLAN-6, AC-5)",
			cond: IndexInvalid, prov: NewFakeProvenance(childName), want: CleanupDropWithProvenance,
		},
		{
			name: "not ready with provenance is dropped",
			cond: IndexNotReady, prov: NewFakeProvenance(childName), want: CleanupDropWithProvenance,
		},
		{
			name: "invalid without provenance halts (FR-PLAN-7, AC-6)",
			cond: IndexInvalid, prov: NewFakeProvenance(), want: CleanupHalt, wantHalt: true,
		},
		{
			name: "invalid with no provenance source at all halts",
			cond: IndexInvalid, prov: nil, want: CleanupHalt, wantHalt: true,
		},
		{
			// A killed DROP INDEX CONCURRENTLY leaves exactly indislive = false
			// with nothing in flight, and PostgreSQL's documented recovery is
			// to reissue the drop. operations/create-index already does that:
			// leafChain's default branch checks provenance and emits a drop.
			// Halting here instead meant `plan` + `execute` could recover from
			// this state and `resume` could not, so every resume attempt failed
			// the run again and the operator's only route was a re-plan.
			name: "not live with provenance is re-dropped (FR-PLAN-6)",
			cond: IndexNotLive, prov: NewFakeProvenance(childName), want: CleanupDropWithProvenance,
		},
		{
			name: "not live without provenance halts (FR-PLAN-7, AC-6)",
			cond: IndexNotLive, prov: NewFakeProvenance(), want: CleanupHalt, wantHalt: true,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got, err := DecideCleanup(ctx(), tc.prov, plan(tc.cond))
			if got != tc.want {
				t.Errorf("decision = %q, want %q", got, tc.want)
			}
			if !tc.wantHalt {
				if err != nil {
					t.Fatalf("unexpected error: %v", err)
				}
				return
			}
			if !errors.Is(err, ErrForeignInvalidIndex) {
				t.Fatalf("err = %v, want ErrForeignInvalidIndex", err)
			}
			// AC-6 wants the halt reported, and the exit code is the
			// authorization-unsatisfied code because that is what refused.
			if code := protocol.ExitCodeFor(err); code != protocol.ExitAuthorizationUnsatisfied {
				t.Errorf("exit code = %d, want 13", code)
			}
			if !strings.Contains(err.Error(), childName.String()) {
				t.Errorf("message %q does not name the index", err.Error())
			}
		})
	}
}

func TestDecideCleanupPropagatesProvenanceErrors(t *testing.T) {
	f := standardTree()
	topo := mustDiscover(t, f)
	leaf := topo.Leaves[0]
	childName := childIndex(t, parentIndexName, leaf.Name.Name)
	existing := idx(indexBase+1, childName.Schema, childName.Name, leaf.OID, leaf.Name.Name, false, true, true)

	prov := NewFakeProvenance()
	prov.Err = errors.New("state store unreachable")

	got, err := DecideCleanup(ctx(), prov, ChildIndexPlan{
		Leaf: leaf, ChildIndex: childName, Condition: IndexInvalid, Existing: &existing,
	})
	if got != CleanupHalt {
		t.Errorf("decision = %q, want %q", got, CleanupHalt)
	}
	if err == nil || !strings.Contains(err.Error(), "state store unreachable") {
		t.Fatalf("err = %v, want the provenance error propagated", err)
	}
}

func TestIndexHelpers(t *testing.T) {
	i := idx(1, "public", "child", 2, "leaf", true, true, true)
	if i.Attached() {
		t.Error("a fresh index should not be attached")
	}
	if i.AttachedTo(0) {
		t.Error("AttachedTo(0) must never be true; 0 means no parent")
	}
	i.ParentIndexOID = 7
	if !i.Attached() || !i.AttachedTo(7) || i.AttachedTo(8) {
		t.Errorf("attachment predicates wrong for %+v", i)
	}
	if i.ConstraintBacked() {
		t.Error("no constraint was set")
	}
	i.ConstraintName, i.ConstraintType = "orders_pkey", "p"
	if !i.ConstraintBacked() {
		t.Error("a constraint-backed index must be reported (FR-DROP-2)")
	}
	if i.String() != "public.child" {
		t.Errorf("String() = %q", i.String())
	}
}

func TestChildIndexPlanCompleteness(t *testing.T) {
	existing := idx(1, "public", "child", 2, "leaf", true, true, true)
	existing.ParentIndexOID = 7

	c := ChildIndexPlan{ChildIndex: name("public", "child"), Existing: &existing, Condition: IndexValid}
	if !c.Complete(7) {
		t.Error("a valid, attached index is complete work (FR-PLAN-5)")
	}
	if c.Complete(8) {
		t.Error("attached to a different parent index is not complete")
	}

	c.Condition = IndexInvalid
	if c.Complete(7) {
		t.Error("an invalid index is never complete")
	}

	empty := ChildIndexPlan{Condition: IndexAbsent}
	if empty.Exists() || empty.AttachedTo(7) || empty.Complete(7) {
		t.Error("an absent index must be absent by every predicate")
	}
}

// TestInspectChildrenAllowsSameBareNameInDifferentSchemas proves the resume
// path agrees with the plan path about what a collision is (FR-PLAN-13, AC-4).
//
// PostgreSQL permits `CREATE TABLE archive.p1 PARTITION OF public.orders`
// alongside `public.p1`, and an index lives in its table's schema, so the two
// leaves cannot collide. operations/create-index proves collision-freedom per
// schema for exactly that reason. InspectChildren, the only path `resume` has,
// must reach the same verdict, or a tree that plans and executes can never be
// resumed.
func TestInspectChildrenAllowsSameBareNameInDifferentSchemas(t *testing.T) {
	f := NewFakeCatalog()
	f.AddRole(ownerOID, "app_owner", true)
	f.AddRelation(Relation{
		OID: rootOID, Name: name("public", "orders"),
		Kind: RelKindPartitionedTable, OwnerOID: ownerOID,
	})
	f.SetStrategy(rootOID, protocol.StrategyRange)
	for i, schema := range []string{"public", "archive"} {
		f.AddRelation(Relation{
			OID: leafOID(i), Name: name(schema, "p1"),
			Kind: RelKindTable, OwnerOID: ownerOID, ParentOID: rootOID,
			PartitionBound: "FOR VALUES FROM ('2026-01-01') TO ('2026-02-01')",
		})
	}

	topo := mustDiscover(t, f)
	in, err := InspectChildren(ctx(), f, topo, name("public", parentIndexName))
	if err != nil {
		t.Fatalf("InspectChildren rejected a legal two-schema tree: %v", err)
	}

	seen := map[protocol.ObjectName]bool{}
	for _, c := range in.Children {
		if c.ChildIndex.Schema != c.Leaf.Name.Schema {
			t.Errorf("child index %v is not in its leaf's schema %q", c.ChildIndex, c.Leaf.Name.Schema)
		}
		if seen[c.ChildIndex] {
			t.Errorf("duplicate child index name %v", c.ChildIndex)
		}
		seen[c.ChildIndex] = true
	}
	if len(seen) != 2 {
		t.Fatalf("got %d distinct child index names, want 2", len(seen))
	}
}
